export function sceneFor(state) {
  const p = state.presentation;
  if (p.view === 'screen' && p.sceneId) return state.scenes[p.sceneId] || null;
  return null;
}

/** The prototype on screen (Prototype view): the presentation carries it whole. */
export function prototypeFor(state) {
  const p = state.presentation;
  return p.view === 'prototype' ? p.prototype || null : null;
}

